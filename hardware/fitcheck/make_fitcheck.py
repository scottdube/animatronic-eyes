#!/usr/bin/env python3
"""Laser fit-check SVG for xTool Creative Space: edge cut + every drilled hole
as RED cut lines, F.SilkS legend as BLACK engrave.  Lasered in 1.5 mm basswood
to prove the part footprints and the outline fit before the mill runs.

Reads the board file only (kicad-cli export is read-only on the project dir,
so KiCad may stay open).  Output: eyes-carrier-fitcheck.svg beside this script.

Why this and not a raw kicad-cli SVG: kicad-cli draws drill marks as FILLED
black discs, the outline in a light grey (#D0D2CD) and silk in pale yellow
(#F2EDA1) -- XCS would engrave the discs solid and Scott could not tell cut
from engrave by colour.  Here holes become stroked circles at the exact drill
diameter (nominal == the bit sizes the footprints were drawn for), the outline
is chained into one closed path so it cuts as one loop, and KiCad's
opacity-0 helper <text> elements are removed so XCS does not import them as
editable text objects.  Component-side (top) view, NOT mirrored: THT parts
load from the top of the wood exactly as on the board.
"""
import re, subprocess, sys, tempfile, pathlib

HERE = pathlib.Path(__file__).resolve().parent
PCB = HERE.parent / "carrier" / "carrier.kicad_pcb"
OUT = HERE / "eyes-carrier-fitcheck.svg"
CLI = "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
CUT, ENGRAVE = "#FF0000", "#000000"

with tempfile.TemporaryDirectory() as td:
    raw = pathlib.Path(td) / "raw.svg"
    subprocess.run([CLI, "pcb", "export", "svg", "--mode-single", "--page-size-mode", "2",
                    "--exclude-drawing-sheet", "--drill-shape-opt", "2",
                    "-l", "Edge.Cuts,F.SilkS", "-o", str(raw), str(PCB)],
                   check=True, capture_output=True)
    svg = raw.read_text()

# --- groups: kicad-cli emits one <g> per plotted colour/layer -------------
groups = re.findall(r"<g style=\"(.*?)\">(.*?)</g>\s*(?=<g style|</svg>)", svg, re.S)
edge = [g for g in groups if "stroke:#D0D2CD" in g[0]]
silk = [g for g in groups if "stroke:#F2EDA1" in g[0]]
drill = [g for g in groups if g[0].startswith("fill:#000000") and "stroke:none" in g[0]]
assert len(edge) == 1 and silk and len(drill) == 1, (len(edge), len(silk), len(drill))   # silk: one <g> per stroke width

# --- edge: chain the line segments into one closed path --------------------
segs = [((float(a), float(b)), (float(c), float(d))) for a, b, c, d in
        re.findall(r"M([\d.]+) ([\d.]+)\s+L([\d.]+) ([\d.]+)", edge[0][1])]
assert segs, "no straight edge segments (arcs would need handling)"
def near(p, q): return abs(p[0] - q[0]) < 0.002 and abs(p[1] - q[1]) < 0.002
segs = [((float(a), float(b)), (float(c), float(d))) for a, b, c, d in
        re.findall(r"M([\d.]+) ([\d.]+)\s+L([\d.]+) ([\d.]+)", edge[0][1])]
first = segs.pop(0)
pts = [first[0], first[1]]
while segs:
    for i, (p, q) in enumerate(segs):
        if near(p, pts[-1]): pts.append(q); segs.pop(i); break
        if near(q, pts[-1]): pts.append(p); segs.pop(i); break
    else:
        sys.exit(f"outline does not chain: {len(segs)} segments left, open end at {pts[-1]}")
assert near(pts[-1], pts[0]), f"outline not closed: {pts[0]} vs {pts[-1]}"
pts = pts[:-1]
outline = "M" + " L".join(f"{x:.4f} {y:.4f}" for x, y in pts) + " Z"

# --- holes: stroked circles at drill diameter -----------------------------
circles = re.findall(r"<circle\s+cx=\"([\d.]+)\" cy=\"([\d.]+)\" r=\"([\d.]+)\" />", drill[0][1])
assert len(circles) == 71, len(circles)   # 67 x 1.181 + 4 x 3.175 on this board
holes = "\n".join(f'<circle cx="{cx}" cy="{cy}" r="{r}" />' for cx, cy, r in circles)
sizes = sorted({round(2 * float(r), 3) for _, _, r in circles})

# --- silk: recolour, drop the invisible helper text -----------------------
def silk_group(style, body):
    body = re.sub(r"<text\b.*?</text>", "", body, flags=re.S)
    return '<g style="%s">%s</g>' % (style.replace("#F2EDA1", ENGRAVE), body)
silk_groups = "\n".join(silk_group(st, body) for st, body in silk)

head = re.search(r"<svg.*?>", svg, re.S).group(0)
# kicad-cli's page-size-mode 2 viewBox is the board bbox with NO stroke margin,
# so the right and bottom edge lines sit half outside it and render clipped.
# Pad 1 mm all round and shift the drawing in by the same amount.
W, H = (float(v) for v in re.search(r'width="([\d.]+)mm" height="([\d.]+)mm"', head).groups())
M = 1.0
head = re.sub(r'width="[\d.]+mm" height="[\d.]+mm" viewBox="[^"]*"',
              f'width="{W + 2*M:.4f}mm" height="{H + 2*M:.4f}mm" viewBox="0 0 {W + 2*M:.4f} {H + 2*M:.4f}"', head)
out = f"""<?xml version="1.0" standalone="no"?>
{head}
<title>EYES CARRIER fit check - red = cut, black = engrave</title>
<desc>Generated by hardware/fitcheck/make_fitcheck.py from carrier.kicad_pcb. Top (component side) view, not mirrored. Board {W:.2f} x {H:.2f} mm. Hole diameters mm: {sizes}</desc>
<g transform="translate({M} {M})">
<g id="cut" style="fill:none; stroke:{CUT}; stroke-width:0.1; stroke-linecap:round; stroke-linejoin:round;">
<path d="{outline}" />
{holes}
</g>
<g id="engrave">
{silk_groups}
</g>
</g>
</svg>
"""
OUT.write_text(out)
print(f"wrote {OUT.relative_to(HERE.parent.parent)}  board {W:.2f} x {H:.2f} mm (+{M} mm margin), outline {len(pts)} vertices, {len(circles)} holes {sizes}")
